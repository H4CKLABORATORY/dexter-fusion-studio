"""Functional quality gate for a narrowly allowlisted Hermes model proposal.

Run only on credential-free GitHub runners BEFORE uploading the generated artifact.
The untrusted module is checked statically, then executed in a bounded child
process with a minimal builtins set, scrubbed environment, and CPU/memory limits.
This is defense-in-depth, not a general-purpose sandbox for arbitrary Python.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from tools.hermes import cloud_ai_worker as worker

MAX_RUNTIME_SECONDS = 5
MIN_CONTRACT_CHECKS = 12

# Trusted subprocess harness, not code generated by the LLM.
_HARNESS = r'''
import copy
import json
import resource
import sys

resource.setrlimit(resource.RLIMIT_CPU, (2, 3))
resource.setrlimit(resource.RLIMIT_AS, (256 * 1024 * 1024, 256 * 1024 * 1024))
allowed = {
    name: getattr(__builtins__, name)
    for name in ("isinstance", "len", "str", "int", "bool", "dict", "list",
                 "tuple", "set", "sorted", "min", "max", "sum", "any", "all",
                 "ValueError", "TypeError", "enumerate", "range", "object")
}
scope = {"__builtins__": allowed}
source = sys.stdin.read()
exec(compile(source, "<hermes-proposal>", "exec"), scope)
summarize = scope["summarize_checkpoint"]
checks = 0

def require(condition, label):
    global checks
    if not condition:
        raise AssertionError(label)
    checks += 1

def rejects(record, label):
    global checks
    try:
        summarize(record)
    except ValueError:
        checks += 1
    else:
        raise AssertionError(label)

base = {
    "task_id": "abc-1",
    "project": "H4CKLABORATORY/demo",
    "status": "in_progress",
    "next_action": "Review PR",
    "blockers": [],
    "last_observed_commit": "a" * 40,
    "last_verified_commit": None,
    "private_token": "NEVER_ECHO_THIS",
}

expected_keys = {
    "task_id", "project", "status", "next_action",
    "blockers_count", "verification_pending"
}
result = summarize(copy.deepcopy(base))
require(isinstance(result, dict) and set(result) == expected_keys, "schema")
require(result["task_id"] == "abc-1", "task_id")
require(result["project"] == "H4CKLABORATORY/demo", "project")
require(result["status"] == "in_progress", "status")
require(result["next_action"] == "Review PR", "next_action")
require(type(result["blockers_count"]) is int and result["blockers_count"] == 0, "blocker count")
require(type(result["verification_pending"]) is bool and result["verification_pending"], "unverified SHA")
require("NEVER_ECHO_THIS" not in str(result), "private data leaked")

modified = copy.deepcopy(base)
before = copy.deepcopy(modified)
summarize(modified)
require(modified == before, "source mutated")

two = copy.deepcopy(base)
two["blockers"] = ["first reason", "second reason"]
out = summarize(two)
require(out["blockers_count"] == 2 and "first reason" not in str(out), "blockers hidden")

same = copy.deepcopy(base)
same["last_verified_commit"] = "a" * 40
require(summarize(same)["verification_pending"] is False, "verified same SHA")

mismatch = copy.deepcopy(base)
mismatch["last_verified_commit"] = "b" * 40
require(summarize(mismatch)["verification_pending"] is True, "stale SHA")

case = copy.deepcopy(base)
case["last_observed_commit"] = "ABCDEF0123456789"
case["last_verified_commit"] = "abcdef0123456789"
require(summarize(case)["verification_pending"] is False, "SHA case normalization")

initial = copy.deepcopy(base)
initial["last_observed_commit"] = None
initial["last_verified_commit"] = None
require(summarize(initial)["verification_pending"] is False, "fresh checkpoint parity")

trim = copy.deepcopy(base)
trim["next_action"] = " Review PR "
trim["project"] = " H4CKLABORATORY/demo "
require(summarize(trim)["next_action"] == "Review PR" and
        summarize(trim)["project"] == "H4CKLABORATORY/demo", "whitespace")

rejects(None, "must reject non-dict")
rejects({}, "must reject missing fields")
bad = copy.deepcopy(base)
bad["blockers"] = "not a list"
rejects(bad, "must reject malformed blockers")
bad = copy.deepcopy(base)
bad["blockers"] = ["ok", 2]
rejects(bad, "must reject mixed blockers")
bad = copy.deepcopy(base)
bad["status"] = "unknown"
rejects(bad, "must reject invalid status")
bad = copy.deepcopy(base)
bad["last_observed_commit"] = "not-a-sha"
rejects(bad, "must reject malformed SHA")
bad = copy.deepcopy(base)
bad["next_action"] = ""
rejects(bad, "must reject empty next action")

print(json.dumps({"passed": True, "checks": checks}))
'''


class ContractError(ValueError):
    pass


def check_source(source: str, timeout_seconds: int = MAX_RUNTIME_SECONDS) -> dict:
    if not 1 <= timeout_seconds <= MAX_RUNTIME_SECONDS:
        raise ContractError("Tiempo máximo fuera de rango")
    # This check is intentionally strict. Never normalize a new artifact in
    # the privileged publishing job.
    try:
        checked = worker.validate_code(source)
    except worker.CloudWorkerError as exc:
        raise ContractError("Propuesta no cumple política AST") from exc
    fn = next(node for node in ast.parse(checked).body if isinstance(node, ast.FunctionDef))
    if not ast.get_docstring(fn):
        raise ContractError("La función debe tener docstring")
    with tempfile.TemporaryDirectory(prefix="hermes-contract-") as scratch:
        env = {"PATH": "/usr/bin:/bin", "HOME": "/nonexistent"}
        try:
            p = subprocess.run(
                [sys.executable, "-I", "-S", "-c", _HARNESS],
                input=checked, encoding="utf-8",
                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                cwd=scratch, env=env, timeout=timeout_seconds, check=False,
            )
        except subprocess.TimeoutExpired as exc:
            raise ContractError("Propuesta excedió tiempo de pruebas funcionales") from exc
    if p.returncode != 0:
        # No raw stdout/stderr from untrusted code in logs.
        raise ContractError("Propuesta rechazó uno o más casos funcionales")
    try:
        report = json.loads(p.stdout)
    except (ValueError, TypeError) as exc:
        raise ContractError("Informe funcional inválido") from exc
    if (report.get("passed") is not True or
            type(report.get("checks")) is not int or
            report["checks"] < MIN_CONTRACT_CHECKS):
        raise ContractError("Cobertura contractual insuficiente")
    return {"schema_version": 1, "passed": True, "checks": report["checks"],
            "sha256": hashlib.sha256(checked.encode("utf-8")).hexdigest(),
            "policy": "hermes-checkpoint-summary-v1"}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Hermes: validar la función de IA sin credenciales")
    p.add_argument("--source", type=Path, required=True)
    p.add_argument("--report", type=Path, required=True)
    args = p.parse_args(argv)
    try:
        text = args.source.read_text(encoding="utf-8")
        report = check_source(text)
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print("Functional contract passed:", report["checks"], "checks")
        return 0
    except (OSError, ValueError) as exc:
        print("Hermes functional gate:", str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
